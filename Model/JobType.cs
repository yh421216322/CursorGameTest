using System;

namespace SurvivalGame.Model
{
    /// <summary>
    /// 工作类型枚举 (JobType)。
    /// 用于表示幸存者或其他单位可以执行的各种工作或任务。
    /// 注释表明此枚举可能是为了与旧系统兼容而保留的。
    /// </summary>
    public enum JobType
    {
        /// <summary>
        /// 空闲状态，未分配任何特定工作。
        /// </summary>
        Idle,        // 空闲

        /// <summary>
        /// 建造工作，负责修建或升级建筑。
        /// </summary>
        Builder,     // 建造工

        /// <summary>
        /// 搜寻/采集工作，负责外出搜集资源。
        /// </summary>
        Forager,     // 搜刮队员 / 采集者

        /// <summary>
        /// 研究工作，负责进行科技研发。
        /// </summary>
        Researcher,  // 研究员

        /// <summary>
        ///守卫工作，负责保卫基地或特定区域。
        /// </summary>
        Guard,       // 守卫

        /// <summary>
        /// 医疗工作，负责治疗伤员。
        /// </summary>
        Medic        // 医护人员
    }
}